// Sort countries alphabetically by name
countries.sort((a, b) => a.name.localeCompare(b.name));

// Get country center coordinates by country name
export const getCountryCenter = (countryName: string | null | undefined): { lat: number; lng: number } | null => {
  if (!countryName) return null;
  
  const country = countries.find(
    c => c.name.toLowerCase() === countryName.toLowerCase()
  );
  
  return country ? country.center : null;
};

// Get default center (US) if country not found
export const getDefaultMapCenter = (countryName?: string | null): { lat: number; lng: number } => {
  const countryCenter = getCountryCenter(countryName);
  return countryCenter || { lat: 39.8283, lng: -98.5795 }; // Default to US center
};
